#!/usr/bin/env python3
"""eval-report.py - Markdown report of eval-gate state for human reading.
"""
import json
import sqlite3
from pathlib import Path
from datetime import datetime, timezone, timedelta

STATE_DIR = Path("/opt/data/state")
DB_PATH = Path("/opt/data/db/eval-gate.db")
OUTPUT = STATE_DIR / "eval-report.md"


def main():
    if not DB_PATH.exists():
        print("No eval-gate.db")
        return
    
    con = sqlite3.connect(str(DB_PATH))
    c = con.cursor()
    
    # Last 30 days
    cutoff = (datetime.now(timezone.utc) - timedelta(days=30)).isoformat()
    c.execute("""
        SELECT id, ts, total, pass_count, fail_count 
        FROM runs WHERE ts > ? ORDER BY ts ASC
    """, (cutoff,))
    rows = c.fetchall()
    
    out = "# Eval-Gate Report\n\n"
    out += f"_Generated: {datetime.now(timezone.utc).isoformat()}_\n\n"
    
    if not rows:
        out += "No runs in last 30 days.\n"
        OUTPUT.write_text(out)
        con.close()
        return
    
    # Aggregate
    total_runs = len(rows)
    total_briefs = sum(r[2] for r in rows)
    total_pass = sum(r[3] for r in rows)
    total_fail = sum(r[4] for r in rows)
    
    out += f"## Summary (Last 30 Days)\n\n"
    out += f"- Runs: {total_runs}\n"
    out += f"- Briefs evaluated: {total_briefs}\n"
    out += f"- Pass: {total_pass}\n"
    out += f"- Fail: {total_fail}\n"
    out += f"- Pass rate: {total_pass/total_briefs*100:.1f}%\n\n"
    
    # Daily breakdown
    daily = {}
    for run_id, ts, total, pass_count, fail_count in rows:
        date = ts[:10]
        if date not in daily:
            daily[date] = {"runs": 0, "briefs": 0, "pass": 0, "fail": 0}
        daily[date]["runs"] += 1
        daily[date]["briefs"] += total
        daily[date]["pass"] += pass_count
        daily[date]["fail"] += fail_count
    
    out += "## Daily Breakdown\n\n"
    out += "| Date | Runs | Briefs | Pass | Fail | Rate |\n"
    out += "|------|------|--------|------|------|------|\n"
    for date in sorted(daily.keys()):
        d = daily[date]
        rate = d["pass"] / d["briefs"] * 100 if d["briefs"] else 0
        out += f"| {date} | {d['runs']} | {d['briefs']} | {d['pass']} | {d['fail']} | {rate:.1f}% |\n"
    
    # Recent failures
    out += "\n## Recent Failures\n\n"
    out += "| Run | TS | Total | Pass | Fail | Rate |\n"
    out += "|-----|-----|-------|------|------|------|\n"
    for run_id, ts, total, pass_count, fail_count in rows[-10:]:
        rate = pass_count / total * 100 if total else 0
        if rate < 70:
            out += f"| {run_id} | {ts[:16]} | {total} | {pass_count} | {fail_count} | {rate:.1f}% |\n"
    
    out += f"\n\n_Generated by eval-report.py_\n"
    
    OUTPUT.write_text(out)
    print(f"Wrote {OUTPUT}")
    print(f"Total: {total_pass}/{total_briefs} = {total_pass/total_briefs*100:.1f}%")
    
    con.close()


